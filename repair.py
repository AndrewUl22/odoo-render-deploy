"""Run on every boot, before Odoo starts.

Render's free tier has an ephemeral filesystem: /var/lib/odoo/filestore is
wiped whenever the service spins down, while the database keeps pointing at
the lost files (-> FileNotFoundError, unstyled pages, 500 on /web/image/...).

1. Store attachments in the database from now on (it survives restarts).
2. Drop attachment records whose file no longer exists. Asset bundles
   (CSS/JS) are regenerated by Odoo on the next request.
"""
import os
import sys

import psycopg2

params = dict(
    host=os.environ["DB_HOST"],
    port=os.environ["DB_PORT"],
    user=os.environ["DB_USER"],
    password=os.environ["DB_PASSWORD"],
    dbname=os.environ["DB_NAME"],
)
filestore = os.path.join("/var/lib/odoo/filestore", os.environ["DB_NAME"])

conn = psycopg2.connect(**params)
cur = conn.cursor()

cur.execute(
    "SELECT to_regclass('public.ir_attachment'), to_regclass('public.ir_config_parameter')"
)
attachment_table, param_table = cur.fetchone()
if not attachment_table or not param_table:
    print("start.sh: repair skipped (database not initialised yet)", flush=True)
    sys.exit(0)

# 1. attachments live in the database from now on
cur.execute(
    """
    INSERT INTO ir_config_parameter (key, value, create_date, write_date)
    VALUES ('ir_attachment.location', 'db', now(), now())
    ON CONFLICT (key) DO UPDATE SET value = 'db', write_date = now()
    """
)
conn.commit()

# 2. forget attachments whose file vanished with the previous container
cur.execute("SELECT id, store_fname FROM ir_attachment WHERE store_fname IS NOT NULL")
missing = [
    att_id
    for att_id, fname in cur.fetchall()
    if not os.path.exists(os.path.join(filestore, fname))
]
removed = 0
if missing:
    try:
        cur.execute("DELETE FROM ir_attachment WHERE id = ANY(%s)", (missing,))
        conn.commit()
        removed = len(missing)
    except Exception as exc:  # e.g. a foreign key: blank the pointer instead
        conn.rollback()
        print("start.sh: delete failed (%s), clearing file pointers instead" % exc, flush=True)
        cur.execute(
            "UPDATE ir_attachment SET store_fname = NULL WHERE id = ANY(%s)", (missing,)
        )
        conn.commit()

conn.close()
print(
    "start.sh: attachment storage set to db; %d orphaned attachment records handled" % len(missing),
    flush=True,
)
